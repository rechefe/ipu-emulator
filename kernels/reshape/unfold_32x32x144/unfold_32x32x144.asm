{#- ==========================================================================
    unfold_32x32x144.asm -- splits a 32x32x144 tensor into its four stride-2 phases

    Rearranges a 32x32x144 spatial tensor (NHCW striped input) into 4
    stride-2 decimated streams of 16x16 tokens, channel-major. TL, TR, BL and
    BR name the PHASE within each 2x2 block (stream s takes phase
    (s // 2, s % 2)), NOT a quadrant of the image.
    Related: unfold_16x16x192 (L4) and unfold_8x8x240 (L5) re-derive this
    kernel's geometry per layer (not direct ports -- the stripe count and
    elements_in_row both change); fold_32x32x144 is its inverse; feeds
    layernorm_256x144.

    Input x (NHCW striped):
      8 stripes x 144 channels; each row = 4 spatial rows x 32 cols = 128
      elements. Row (stripe, ch) at x + stripe x 144 + ch.

    Output y (two token groups per channel, stream after stream):
      Stream s, channel c, token group t: row c*2 + t of stream s.
      A channel's 256 tokens (its 16x16 decimated grid, row-major) fill two
      whole rows: tg=0 holds decimated rows 0..7, tg=1 decimated rows 8..15.
      Every lane is valid; there is no stale tail.

    Pass-through multiply: MULT.RC.VV with R_CYCLIC holding 1.0 in every lane
    (loaded once from the ones row at startup, never overwritten in the loop)
    and the stripe row in R0 (LD.MULT R0):
      MULT.RC.VV acc_slot0 R0 0 acc_slot0: R0[i] x R_CYCLIC[i] = stripe[i].
    No R_ACC reset is needed: the 4 ACC.STRIDE calls of a token group
    overwrite all 4 R_ACC slots.

    Streams (ACC.STRIDE with elements_in_row=32):
      128 elements from one stripe = 4 rows x 32 cols
      TL (stream 0): ACC.STRIDE 32 on     on     -> even cols, even rows
      TR (stream 1): ACC.STRIDE 32 on_inv on     -> odd  cols, even rows
      BL (stream 2): ACC.STRIDE 32 on     on_inv -> even cols, odd  rows
      BR (stream 3): ACC.STRIDE 32 on_inv on_inv -> odd  cols, odd  rows
    ACC.STRIDE encodings:
      horizontal: on=1 (even cols), on_inv=2 (odd cols)
      vertical:   on=1 (even rows), on_inv=2 (odd rows)
    Each ACC.STRIDE call selects 32 of the 128 MULT results (2 rows x 16
    cols) into one 32-element R_ACC slot (slot 0..3). Four calls, one per
    stripe of the token group, fill the whole 128-element accumulator.

    ABI: kernel.toml's [abi] binds the CRs below.
      CR0          x's stripe 0, read through the hardwired 0: x must sit at
                   row 0
      CR13         x's stripe 1 (CR1 is read-only, so not CR1)
      CR2..CR7     x's stripes 2..7
      CR8          the ones row (R_CYCLIC's 1.0 multiplier)
      CR9..CR12    streams TL, TR, BL, BR of y
      CR14.H       the channel loop's bound (144), above the QF half
    LR0 (R_CYCLIC slot 0, mask immediate, ACC.STRIDE slot 0), LR4 (source
    row offset within each stripe), LR8 (token group 0's destination row
    offset) and LR10 (channel counter) are set by the program's first words (the row strides are the hardwired CR1)
    (hardwired 1) is the channel loop's increment. CR0 and CR1 are
    read-only: a host write to either raises.

    MULT CYCLE-START CONTRACT (issue #157): MULT.RC.VV reads its R0 data as it
    was at the start of the cycle, so a MULT cannot consume a row loaded by an
    LD.MULT in its own instruction word -- it would see the PREVIOUS
    contents of R0. `;;` ends one instruction word = one cycle and `;`
    separates the instructions within it, so a load and a MULT in the same
    word always execute in the same cycle regardless of textual order:
    co-issuing them is fine, consuming the same-cycle load is not.

    The 32 loads per channel form a fixed sequence -- 8 (stream, token-group)
    groups x 4 stripes -- so the fix is a pure one-word rotation: the first
    load is primed before ch_loop, and word i multiplies the row loaded by
    word i-1 while prefetching the row word i+1 will multiply. The final
    load of a channel wraps to stripe 0 of the NEXT channel, which is why
    src_off advances just before it (LR slots run ahead of LOAD within a
    word, so that ADD cannot share a word with the load that consumes it).
    The body is generated by a Jinja loop over that sequence so the rotation
    stays consistent across all 32 sites.

    Registers are referred to below by the symbolic names defined in the
    register-name block. The assembler's Jinja2 preprocessor substitutes them
    before parsing, so the emitted binary is byte-identical to the raw form;
    the register-name block is the single source of truth for this kernel's
    register use. NOTE: Jinja runs before comment stripping, so '#' comments
    in the program must not contain Jinja delimiters -- the preprocessor
    would try to execute them.
========================================================================== -#}

# ---------------------------------------------------------------------------
# Initialisation
# ---------------------------------------------------------------------------
# The program sets every LR it reads. Slots 0 and 1 and the row offsets in the
# two entry words; slots 2 and 3 (2 and 3, built from slot 1) in the first
# stream's first two words, before the ACC.STRIDE that reads each.

# ---------------------------------------------------------------------------
# Register names (Jinja2 preprocessor; pure source-level substitution)
# ---------------------------------------------------------------------------
{% set acc_slot0   = "LR0"  %}  {# const 0: r_cyclic slot / mask imm / ACC.STRIDE slot 0 #}
{% set acc_slot1   = "LR1"  %}  {# const 1: ACC.STRIDE r_acc slot 1 -> [32..63] #}
{% set acc_slot2   = "LR2"  %}  {# const 2: ACC.STRIDE r_acc slot 2 -> [64..95] #}
{% set acc_slot3   = "LR3"  %}  {# const 3: ACC.STRIDE r_acc slot 3 -> [96..127] #}
{% set src_off     = "LR4"  %}  {# source row offset within each stripe (= ch) #}
{% set src_stride  = "CR1"  %}  {# 1 = source row stride per channel: the hardwired 1 #}
{% set dst_stride  = acc_slot2  %}  {# 2 = destination row stride per channel (tg0, tg1): the same constant as slot 2 #}
{% set dst_off_tg0 = "LR8"  %}  {# tg=0 destination row offset = ch*2 #}
{% set dst_off_tg1 = "LR9"  %}  {# tg=1 destination row offset = ch*2 + 1 #}
{% set ch_index    = "LR10" %}  {# channel counter (0..143) #}
{% set ch_limit    = cr.qf ~ ".H"  %}  {# 144 = channel count: CR14's free high half #}

{% set STRIPE0_TG0 = "CR0"  %}  {# x + 0*144 rows (stripe 0) #}
{% set ONE         = "CR1"  %}  {# hardwired read-only 1 #}
{% set STRIPE2_TG0 = "CR2"  %}  {# x + 2*144 rows (stripe 2) #}
{% set STRIPE3_TG0 = "CR3"  %}  {# x + 3*144 rows (stripe 3) #}
{% set STRIPE0_TG1 = "CR4"  %}  {# x + 4*144 rows (stripe 4) #}
{% set STRIPE1_TG1 = "CR5"  %}  {# x + 5*144 rows (stripe 5) #}
{% set STRIPE2_TG1 = "CR6"  %}  {# x + 6*144 rows (stripe 6) #}
{% set STRIPE3_TG1 = "CR7"  %}  {# x + 7*144 rows (stripe 7) #}
{% set ONES_BASE   = "CR8"  %}  {# one row of 1.0 (R_CYCLIC init) #}
{% set DST_TL      = "CR9"  %}  {# stream TL output base #}
{% set DST_TR      = "CR10" %}  {# stream TR output base #}
{% set DST_BL      = "CR11" %}  {# stream BL output base #}
{% set DST_BR      = "CR12" %}  {# stream BR output base #}
{% set STRIPE1_TG0 = "CR13" %}  {# x + 1*144 rows (stripe 1) #}
{% set DSTRUCT     = "CR15" %}  {# reserved dstructure register #}

{% set groups = [
     ("TL", "on",     "on",     "tg0", DST_TL, STRIPE0_TG0, STRIPE1_TG0, STRIPE2_TG0, STRIPE3_TG0),
     ("TL", "on",     "on",     "tg1", DST_TL, STRIPE0_TG1, STRIPE1_TG1, STRIPE2_TG1, STRIPE3_TG1),
     ("TR", "on_inv", "on",     "tg0", DST_TR, STRIPE0_TG0, STRIPE1_TG0, STRIPE2_TG0, STRIPE3_TG0),
     ("TR", "on_inv", "on",     "tg1", DST_TR, STRIPE0_TG1, STRIPE1_TG1, STRIPE2_TG1, STRIPE3_TG1),
     ("BL", "on",     "on_inv", "tg0", DST_BL, STRIPE0_TG0, STRIPE1_TG0, STRIPE2_TG0, STRIPE3_TG0),
     ("BL", "on",     "on_inv", "tg1", DST_BL, STRIPE0_TG1, STRIPE1_TG1, STRIPE2_TG1, STRIPE3_TG1),
     ("BR", "on_inv", "on_inv", "tg0", DST_BR, STRIPE0_TG0, STRIPE1_TG0, STRIPE2_TG0, STRIPE3_TG0),
     ("BR", "on_inv", "on_inv", "tg1", DST_BR, STRIPE0_TG1, STRIPE1_TG1, STRIPE2_TG1, STRIPE3_TG1)
   ] %}
{% set slots = [acc_slot0, acc_slot1, acc_slot2, acc_slot3] %}

    SET                 {{ acc_slot0 }} CR0;                               # slot 0
    SET                 {{ acc_slot1 }} CR1;                               # slot 1
    SET                 {{ src_off }} CR0;                                 # source row offset
    LD.MULT.CYCLIC {{ acc_slot0 }} {{ ONES_BASE }} {{ acc_slot0 }};;  # r_cyclic[0..127] = 1.0

    SET                 {{ dst_off_tg0 }} CR0;                             # destination row offsets
    SET                 {{ dst_off_tg1 }} CR1;
    SET                 {{ ch_index }} CR0;                                # channel counter
    LD.MULT        R0 {{ src_off }} {{ STRIPE0_TG0 }};;               # prime: stripe 0, tg=0 of ch 0

# ---------------------------------------------------------------------------
# Main channel loop  (ch = 0..143)
# ---------------------------------------------------------------------------

ch_loop:

    # Word i multiplies the row loaded by word i-1 and prefetches the
    # row word i+1 will multiply (MULT cycle-start contract, see header).
{% for g in groups %}
    # -- Stream {{ g[0] }}  ({{ g[3] }}: h={{ g[1] }}, v={{ g[2] }}) --
{%- set gi = loop.index0 %}
{%- for s in range(4) %}
{#- The row to PREFETCH is the next entry in the flat 32-load sequence. #}
{%- set ni = (gi * 4 + s + 1) % 32 %}
{%- set ng = groups[ni // 4] %}
{%- set nstripe = ng[5 + (ni % 4)] %}
{%- if ni == 0 %}
    # Last load of the channel wraps to stripe 0 of the NEXT channel, so
    # src_off must advance in the word BEFORE it (LR slots precede LOAD).
    ADD                 {{ src_off }} {{ src_off }} {{ src_stride }};;     # src offset: next channel (+1 row)
{%- endif %}
{%- if gi == 0 and s == 0 %}
    ADD                 {{ acc_slot2 }} {{ acc_slot1 }} {{ ONE }};         # slot 2 = 2 (set again every channel: harmless)
{%- elif gi == 0 and s == 1 %}
    ADD                 {{ acc_slot3 }} {{ acc_slot2 }} {{ ONE }};         # slot 3 = 3
{%- endif %}
    LD.MULT R0 {{ src_off }} {{ nstripe }};
    MULT.RC.VV {{ acc_slot0 }} R0 0 {{ acc_slot0 }} {{ DSTRUCT }}.L {{ cr.qf }}.L;
    ACC.STRIDE 32 {{ g[1] }} {{ g[2] }} {{ slots[s] }};;
{%- endfor %}
    ACTIVATE.EXACT   identity {{ DSTRUCT }}.L {{ g[4] }} {{ g[3] == "tg0" and dst_off_tg0 or dst_off_tg1 }};; # {{ g[0] }} {{ g[3] }}
{% endfor %}
    ADD                 {{ dst_off_tg0 }} {{ dst_off_tg0 }} {{ dst_stride }};
    ADD {{ dst_off_tg1 }} {{ dst_off_tg1 }} {{ dst_stride }};;  # dst offsets: +2 rows per channel
    ADD                 {{ ch_index }} {{ ch_index }} {{ ONE }};;
    BLT.S                 {{ ch_index }} {{ ch_limit }} ch_loop;;            # loop while ch < 144

end:
    HALT;;
