"""Prototyping mode: opt-in shortcuts that are not a faithful chip model.

The default emulator models what the hardware does, cycle by cycle and slot by
slot: every slot is dispatched even when it holds a NOP, every multiply applies
its element mask, every operand is read through the register file's accessors.
That fidelity is the point — it is what makes the emulator answerable about the
chip. Both modes take the same cycle-start register snapshot.

Prototyping mode trades some of it for speed on long runs (a full-image
convolution, a sweep over shapes) where the question is "what does this kernel
compute" rather than "what does the chip do". It differs in four places, and
nowhere else:

1. schedules skip the idle NOP slots (``Cycle(skip_idle_nops=...)``,
   :func:`ipu_emu.cycle.schedule_word`);
2. read operands go through the packed resolver
   (:class:`ipu_emu.resolver.PackedResolver`, picked by
   :func:`ipu_emu.cycle.resolver_for`);
3. a MULT with no mask shift whose R_MASK slot is all ones skips the mask
   pipeline (``ipu_emu.slots.mult``); and
4. an ``ACTIVATE.EXACT`` (FP32 mode) of ``identity``, ``exp2`` or
   ``reciprocal`` over all LANES lanes runs as one batched row
   (``ipu_emu.slots.aaq_exact``).

These shortcuts are:

* provably result-preserving — the state after every cycle is **bit-identical**
  to the faithful path, and ``test_prototyping_equivalence.py`` pins registers,
  XMEM, exceptions, and snapshots including batched full-row FP32 activations;
  and
* **not** a description of the hardware — a skipped NOP slot still occupies its
  slot in the real machine, and a skipped mask is still applied there.

So it is safe to trust the numbers a prototyping run produces, and wrong to
reason from it about what the chip spends a cycle on.

The Bazel build flag is a mandatory capability gate:

1. ``bazel run --define=ipu_proto=1 //...`` generates ``_build_flags.py`` with
   prototyping support enabled and makes it the default;
2. inside that flagged build, ``IpuState(prototyping=...)`` may select the mode
   per state; and
3. inside that flagged build, ``IPU_EMU_PROTOTYPING`` may select the process
   default. The value is case-insensitive: ``0``/``false``/``no``/``off``/empty
   mean off, ``1``/``true``/``yes``/``on`` mean on, anything else raises.

A build without the flag, including a plain checkout, cannot activate the fast
paths. A positive runtime request in such a build raises ``ConfigurationError`` (a
``ValueError``).
"""

from __future__ import annotations

import os

from ipu_emu.errors import ConfigurationError

try:  # generated by the Bazel genrule; absent in a plain checkout
    from ipu_emu._build_flags import PROTOTYPING as _BUILD_DEFAULT
except ImportError:  # pragma: no cover - depends on the build, not the code
    _BUILD_DEFAULT = False

_FALSEY = frozenset({"", "0", "false", "no", "off"})
_TRUTHY = frozenset({"1", "true", "yes", "on"})


def env_requests_prototyping(raw: str) -> bool:
    """Parse an ``IPU_EMU_PROTOTYPING`` value, ignoring case and surrounding whitespace.

    ``0``, ``false``, ``no``, ``off`` and the empty string mean off; ``1``,
    ``true``, ``yes`` and ``on`` mean on. Any other value raises ``ValueError``.
    """
    value = raw.strip().lower()
    if value in _FALSEY:
        return False
    if value in _TRUTHY:
        return True
    raise ConfigurationError(
        f"IPU_EMU_PROTOTYPING={raw!r} is not a recognised value; use one of "
        "0/false/no/off/'' (off) or 1/true/yes/on (on), in any case"
    )


def default_enabled() -> bool:
    """Whether a new :class:`~ipu_emu.ipu_state.IpuState` starts in prototyping mode."""
    env = os.environ.get("IPU_EMU_PROTOTYPING")
    requested = bool(_BUILD_DEFAULT) if env is None else env_requests_prototyping(env)
    return resolve_enabled(requested)


def build_enabled() -> bool:
    """Whether this build is allowed to execute prototyping fast paths."""
    return bool(_BUILD_DEFAULT)


def resolve_enabled(requested: bool | None) -> bool:
    """Resolve a per-state request without allowing it to bypass the build gate."""
    if requested is None:
        return default_enabled()
    enabled = bool(requested)
    if enabled and not build_enabled():
        raise ConfigurationError(
            "prototyping mode requires a Bazel build with --define=ipu_proto=1"
        )
    return enabled
