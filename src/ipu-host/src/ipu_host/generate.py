"""Artifacts generated from the register maps.

``write_register_blocks`` writes one SystemVerilog register block per map
(PeakRDL regblock, AXI4-Lite CPU interface): ``<map>_regs.sv``, its package
``<map>_regs_pkg.sv``, and ``<map>_addr_pkg.sv`` with every address. ``register_map_markdown`` renders the tables
of the docs page.
"""

from __future__ import annotations

from pathlib import Path

from peakrdl_regblock import RegblockExporter
from peakrdl_regblock.cpuif.axi4lite import AXI4Lite_Cpuif_flattened

from ipu_host.regmap import MAP_NAMES, Field, RegisterMap, elaborate, load

#: Base of each map in the FPGA prototype kernel's control address space
#: (docs/content/specs/fpga-prototype.md, "Control address map").
PROTOTYPE_BASES = {"ipu_host": 0x00000, "proto_platform": 0x20000}

#: Size of the kernel's control address space on the prototype.
PROTOTYPE_CONTROL_SPACE = 0x40000


def write_register_blocks(out_dir: Path) -> list[Path]:
    """Write ``<map>_regs.sv``, ``<map>_regs_pkg.sv`` and ``<map>_addr_pkg.sv`` for every map.

    Returns:
        The files written.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name in MAP_NAMES:
        RegblockExporter().export(
            elaborate(name),
            str(out_dir),
            cpuif_cls=AXI4Lite_Cpuif_flattened,
            module_name=f"{name}_regs",
            package_name=f"{name}_regs_pkg",
            # IPU-IF-2: rst_n, asserted asynchronously, active low.
            default_reset_activelow=True,
            default_reset_async=True,
        )
        addr = out_dir / f"{name}_addr_pkg.sv"
        addr.write_text(address_package(name))
        written += [out_dir / f"{name}_regs.sv", out_dir / f"{name}_regs_pkg.sv", addr]
    return written


def address_package(name: str) -> str:
    """The SystemVerilog package ``<name>_addr_pkg``: every register's and
    memory's byte address as a localparam.

    The regblock answers every access with OKAY, so the IPU checks the access
    rules (IPU-HOST-5) in front of it; the checker decodes with these.
    """
    regmap = load(name)
    width = max(1, (regmap.size - 1).bit_length())
    lines = [
        "// Generated by `bazel run //src/ipu-host:ipu-host -- sv`. Edit the .rdl files.",
        f"package {name}_addr_pkg;",
        f"  localparam int unsigned ADDR_WIDTH = {width};",
        f"  localparam int unsigned MAP_SIZE = 'h{regmap.size:X};",
    ]
    for mem in regmap.memories.values():
        ident = _identifier(mem.path)
        lines.append(f"  localparam logic [{width - 1}:0] {ident}_ADDR = 'h{mem.address:X};")
        lines.append(f"  localparam int unsigned {ident}_SIZE = 'h{mem.size:X};")
    for reg in regmap.registers.values():
        ident = _identifier(reg.path)
        lines.append(f"  localparam logic [{width - 1}:0] {ident}_ADDR = 'h{reg.address:X};")
    lines.append("endpackage")
    return "\n".join(lines) + "\n"


def _identifier(path: str) -> str:
    """``REGS.CR_BANK[1].CR[3]`` -> ``REGS_CR_BANK1_CR3``."""
    return path.replace("].", "_").replace("[", "").replace("]", "").replace(".", "_")


def register_map_markdown() -> str:
    """The register tables of every map, as Markdown."""
    parts = [
        "<!-- Generated by `bazel run //src/ipu-host:ipu-host -- docs`. Edit the .rdl files. -->",
        "",
        "# Register maps",
        "",
        "Generated from `src/ipu-host/src/ipu_host/rdl/`. Offsets are bytes from the base of the map.",
    ]
    for name in MAP_NAMES:
        parts += ["", *_map_markdown(load(name))]
    return "\n".join(parts) + "\n"


def _map_markdown(regmap: RegisterMap) -> list[str]:
    base = PROTOTYPE_BASES[regmap.name]
    lines = [
        f"## `{regmap.name}`",
        "",
        f"Size 0x{regmap.size:X} bytes, at 0x{base:05X} in the prototype's control space.",
        "",
        "| Offset | Path | Size |",
        "|---|---|---|",
    ]
    lines += [
        f"| 0x{m.address:05X} | `{m.path}` | {m.size} bytes |" for m in regmap.memories.values()
    ]
    lines += ["", "| Offset | Register | Fields | Reset |", "|---|---|---|---|"]
    for reg in regmap.registers.values():
        fields = ", ".join(_field_text(f) for f in sorted(reg.fields.values(), key=_lsb))
        external = " (external)" if reg.external else ""
        lines.append(
            f"| 0x{reg.address:05X} | `{reg.path}`{external} | {fields} | 0x{reg.reset:08X} |"
        )
    return lines


def _lsb(field: Field) -> int:
    return field.lsb


def _field_text(field: Field) -> str:
    access = ("R" if field.sw_readable else "") + ("W" if field.sw_writable else "")
    msb = field.lsb + field.width - 1
    bits = f"{field.lsb}" if field.width == 1 else f"{msb}:{field.lsb}"
    return f"`{field.name}`[{bits}] {access}"
